lucide.createIcons();

const chat = document.getElementById("chat-container");
const input = document.getElementById("user-input");
const btn = document.getElementById("send-btn");

const modal = document.getElementById("settings-modal");
const openModal = document.getElementById("settings-trigger");
const saveKey = document.getElementById("save-key-btn");
const closeModal = document.getElementById("close-modal");
const keyInput = document.getElementById("api-key-input");

let KEY = localStorage.getItem("dipx_key") || "";

openModal.onclick = () => modal.classList.remove("hidden");
closeModal.onclick = () => modal.classList.add("hidden");

saveKey.onclick = () => {
  KEY = keyInput.value;
  localStorage.setItem("dipx_key", KEY);
  modal.classList.add("hidden");
};

function addMsg(text, type){
  const div = document.createElement("div");
  div.className = `message ${type}`;
  div.textContent = text;
  chat.appendChild(div);
  chat.scrollTop = chat.scrollHeight;
  return div;
}

async function send(){
  const prompt = input.value.trim();
  if(!prompt) return;
  if(!KEY){ modal.classList.remove("hidden"); return; }

  addMsg(prompt,"user-message");
  input.value = "";

  const loader = addMsg("Thinking...","ai-message");

  try{
    const res = await fetch("https://api.openai.com/v1/responses",{
      method:"POST",
      headers:{
        "Content-Type":"application/json",
        "Authorization":`Bearer ${KEY}`
      },
      body:JSON.stringify({
        model:"gpt-5.3",
        input:prompt
      })
    });

    const data = await res.json();
    loader.remove();

    addMsg(data.output[0].content[0].text,"ai-message");

  }catch(e){
    loader.remove();
    addMsg("Error connecting to AI","ai-message");
  }
}

btn.onclick = send;

input.addEventListener("keydown",e=>{
  if(e.key==="Enter" && !e.shiftKey){
    e.preventDefault();
    send();
  }
});
